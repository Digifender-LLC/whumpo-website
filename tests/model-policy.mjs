import assert from 'node:assert/strict';
import {inferenceCost,planningRates,museTestRoute,evaluateEscalation,subagentAdmission} from '../src/model-policy.ts';
assert.equal(inferenceCost(planningRates.orchestrator,12000,1000),700);
assert.equal(inferenceCost(planningRates.normal,40000,4000),4800);
assert.equal(inferenceCost(planningRates.advanced,80000,6000),165000);
assert.equal(inferenceCost(planningRates.normal,1,0),1);
assert.equal(inferenceCost(planningRates.normal,100,0,100),10); // no assumed cache discount
assert.throws(()=>inferenceCost(planningRates.normal,-1,0));
assert.throws(()=>inferenceCost(planningRates.normal,1,0,2));
assert.throws(()=>inferenceCost(planningRates.advanced,Number.MAX_SAFE_INTEGER,Number.MAX_SAFE_INTEGER));
const config={baseURL:'https://opencode.ai/zen/go/v1',model:'muse-spark-1.3-contributor',apiKey:'test'};
for(const role of ['orchestrator','normal','advanced'])assert.equal(museTestRoute(config,role).config.model,config.model);
assert.throws(()=>museTestRoute({...config,model:'expensive-model'}));
assert.throws(()=>museTestRoute({...config,baseURL:'https://evil.test'}));
const evidence={normalAttemptFailed:true,failedFixAttempts:2,testsStillFailing:true,lowConfidence:false,capabilityMismatch:false,repeatedInvalidTools:false,unexpectedDeployment:false,requestedEscalation:false,necessity:'medium',alreadyStartedCritical:false,transientFailureOnly:false};
assert.equal(evaluateEscalation(evidence,15000000,20000000).allowed,true);
assert.equal(evaluateEscalation({...evidence,normalAttemptFailed:false},15000000,20000000).allowed,false);
assert.equal(evaluateEscalation({...evidence,transientFailureOnly:true},15000000,20000000).allowed,false);
assert.equal(evaluateEscalation({...evidence,necessity:'low'},10000000,20000000).allowed,false);
assert.equal(evaluateEscalation(evidence,4000000,20000000).allowed,false);
assert.equal(evaluateEscalation({...evidence,necessity:'high'},4000000,20000000).allowed,true);
assert.equal(evaluateEscalation({...evidence,necessity:'high'},1000000,20000000).allowed,false);
assert.equal(evaluateEscalation({...evidence,necessity:'high',alreadyStartedCritical:true},1000000,20000000).allowed,true);
assert.equal(evaluateEscalation({...evidence,necessity:'high',alreadyStartedCritical:true},0,20000000).allowed,false);
const state={activeSubagents:0,advanced30Days:0,advanced24Hours:0,remainingMicros:15000000,budgetMicros:20000000,quotedMicros:100000};
assert.equal(subagentAdmission('advanced',state).allowed,false);
assert.equal(subagentAdmission('advanced',state,evidence).allowed,true);
assert.equal(subagentAdmission('advanced',{...state,advanced30Days:150},evidence).allowed,false);
assert.equal(subagentAdmission('advanced',{...state,advanced24Hours:20},evidence).allowed,false);
assert.equal(subagentAdmission('normal',{...state,activeSubagents:2}).allowed,false);
assert.equal(subagentAdmission('normal',{...state,quotedMicros:16000000}).allowed,false);
console.log('Model policy passed: Muse-only routes, exact planning costs, no cache assumption, budget thresholds, evaluator gating, 2-agent/150-month/20-day admission.');
