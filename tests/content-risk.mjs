import assert from 'node:assert/strict';
import {assessContentRisk} from '../src/content-risk.ts';
const day=86400000, now=Date.UTC(2026,8,30), userId='fixture-owner';
const event=(incidentId,kind,age=0,extra={})=>({userId,incidentId,kind,occurredAt:now-age*day,disposition:'active',...extra});
const assess=(events=[],complete=true)=>assessContentRisk({userId,complete,events},now);
assert.equal(assess().supplementalTextScanPercent,25);
const benign=Array.from({length:28},(_,i)=>event(`benign-${i}`,'verified_benign',i%7));
const trusted=assess(benign);
assert.equal(trusted.established,true);assert.equal(trusted.supplementalTextScanPercent,5);
assert.equal(trusted.generatedArtifactScanPercent,10);
assert.equal(assessContentRisk({userId,complete:true,events:benign,currentContentFlag:true},now).supplementalTextScanPercent,100);
assert.equal(assess([...benign,event('faded-flag','uncertain_flag',89)]).established,false);
for(const value of Object.values(trusted.baseline)) assert.equal(value,true);
assert.equal(assess(benign,false).supplementalTextScanPercent,100);
assert.equal(assess(benign.slice(0,19)).established,false);
assert.equal(assess(benign.map(e=>({...e,occurredAt:now}))).established,false);
const violation=event('violation','confirmed_violation');
assert.equal(assess([violation]).score,15);
assert.equal(assess([violation,violation]).score,15);
assert.equal(assess([violation,event('second','confirmed_violation')]).score,40);
assert.equal(assess([event('a','confirmed_evasion'),event('b','confirmed_evasion')]).band,'high');
assert.equal(assess([event('a','confirmed_evasion'),event('b','confirmed_evasion'),event('c','confirmed_evasion')]).reviewRequired,true);
assert.equal(assess([event('a','confirmed_evasion')]).supplementalTextScanPercent,100);
assert.equal(assess([event('a','confirmed_violation',30)]).score,8);
assert.equal(assess([event('a','confirmed_violation',91)]).score,0);
assert.equal(assess(Array.from({length:100},(_,i)=>event(`u-${i}`,'uncertain_flag'))).score,10);
const critical=event('critical','critical_incident',365);
assert.equal(assess([...benign,critical]).score,100);
assert.equal(assess([...benign,critical]).automaticAccountBlock,false);
assert.equal(assess([critical,{...critical,disposition:'overturned'}]).score,0);
assert.equal(assess([{...critical,disposition:'overturned'},critical]).score,0);
assert.equal(assess([violation,event('violation','confirmed_evasion')]).score,25);
assert.equal(assess([event('same','confirmed_violation',30),event('same','confirmed_violation')]).score,8);
for(const bad of [{userId:'other'},{occurredAt:now+1},{kind:'toString'},{disposition:'unknown'},{incidentId:''}])assert.throws(()=>assess([event('a','confirmed_violation',0,bad)]));
assert.throws(()=>assessContentRisk({userId,complete:true,events:[]},NaN));
console.log('Content-risk policy passed: tenant isolation, deduplication, decay, repeated evasion, reversals, uncertainty cap, missing history, trust qualification, mandatory media/import gates, and no automatic ban.');
