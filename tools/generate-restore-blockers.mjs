// WH-019: derives src/restore-blockers.generated.ts from the canonical schema. When a restore replay removes an account or project the ledger says is gone,
// rows that still reference them with RESTRICT or NO ACTION (closure cleared these live before it could purge) would stop the final delete on every attempt.
// The foreign keys are read here, in Node, because the production D1 engine does not authorize PRAGMA foreign_key_list at run time. If the schema changes,
// `--check` (part of `pnpm check`) fails until this is regenerated. Run `node tools/generate-restore-blockers.mjs`, or with `--check` to compare only.
import {readFile,writeFile} from 'node:fs/promises';
import {DatabaseSync} from 'node:sqlite';
import {currentSchema} from './current-schema.mjs';

const output='src/restore-blockers.generated.ts';
const db=new DatabaseSync(':memory:');db.exec(await currentSchema());
const quoted=name=>'"'+name.replaceAll('"','""')+'"';
const ids=kind=>`(SELECT subject_id FROM restore_suppressions WHERE kind='${kind}')`;
const keysTo=db.prepare(`SELECT m.name AS child,f."from" AS col,coalesce(f."to",'id') AS pk,f.on_delete AS onDelete FROM sqlite_master m,pragma_foreign_key_list(m.name) f WHERE m.type='table' AND m.name NOT LIKE 'sqlite_%' AND f."table"=?1 ORDER BY m.name,f."from"`);
/** (table, condition) pairs for every RESTRICT / NO ACTION child below `parent`, walking cascade chains as well. */
function conditions(parent,filter,path=[]){
 if(path.length>8)throw Error('Foreign key chain deeper than the replay supports under '+parent);
 const out=[];
 for(const fk of keysTo.all(parent)){
  if(fk.child===parent||path.includes(fk.child))continue;
  const inner=`${quoted(fk.col)} IN (SELECT ${quoted(fk.pk)} FROM ${quoted(parent)} WHERE ${filter})`;
  out.push(...conditions(fk.child,inner,[...path,parent]));
  if(fk.onDelete==='NO ACTION'||fk.onDelete==='RESTRICT')out.push({table:fk.child,cond:inner});
 }
 return out;
}
const roots=[{parent:'users',filter:`id IN ${ids('account')}`},{parent:'projects',filter:`id IN ${ids('project')} OR owner_user_id IN ${ids('account')}`}];
const byTable=new Map();
for(const {parent,filter} of roots)for(const {table,cond} of conditions(parent,filter))byTable.set(table,(byTable.get(table)??new Set()).add(cond));
// A table is cleared before the tables it references: whoever references it goes first.
const order=[],visiting=new Set(),done=new Set();
const visit=table=>{
 if(done.has(table)||visiting.has(table))return;
 visiting.add(table);
 for(const fk of keysTo.all(table))if(byTable.has(fk.child))visit(fk.child);
 visiting.delete(table);done.add(table);order.push(table);
};
for(const table of [...byTable.keys()].sort())visit(table);
// D1 refuses an expression tree deeper than 100, and an OR chain is as deep as it is long, so a table's conditions go in statements of at most 20 each.
const chunk=(list,size)=>Array.from({length:Math.ceil(list.length/size)},(_,i)=>list.slice(i*size,(i+1)*size));
const statements=order.flatMap(table=>chunk([...byTable.get(table)].sort(),20).map(part=>`DELETE FROM ${quoted(table)} WHERE ${part.map(c=>`(${c})`).join(' OR ')}`));
const file=`// Generated by tools/generate-restore-blockers.mjs from the canonical schema. Do not edit: run \`node tools/generate-restore-blockers.mjs\`.
// One delete per table that references a ledgered account or project with RESTRICT or NO ACTION (directly or below a cascade), each table before the tables it references.
export const restoreBlockerStatements:readonly string[]=${JSON.stringify(statements,null,1)};
`;
if(process.argv.includes('--check')){if(await readFile(output,'utf8')!==file)throw Error('Restore blocker statements are stale; run node tools/generate-restore-blockers.mjs');}
else await writeFile(output,file);
