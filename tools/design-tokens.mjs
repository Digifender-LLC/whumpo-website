// Generates frontend/src/design-tokens.css, public-app/design-tokens.css and the Android Compose theme tokens
// (android/shared/.../theme/WhumpoTokens.kt) from the design system's tokens.json.
// Usage: node tools/design-tokens.mjs [--check]
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';

const source=new URL('../docs/design/whumpo-design-system/tokens.json',import.meta.url);
const targets=[['frontend/src/design-tokens.css',false],['public-app/design-tokens.css',true]].map(([path,media])=>({path,media,url:new URL('../'+path,import.meta.url)}));

const luminance=hex=>{const [r,g,b]=[1,3,5].map(i=>parseInt(hex.slice(i,i+2),16)/255).map(c=>c<=.03928?c/12.92:((c+.055)/1.055)**2.4);return .2126*r+.7152*g+.0722*b;};
export const contrast=(a,b)=>{const [x,y]=[luminance(a),luminance(b)].sort((m,n)=>n-m);return (x+.05)/(y+.05);};
// Every text token pair the UI uses must reach 4.5:1 in both themes (WCAG AA, normal text).
const textPairs=[
 ['ink',['surface','surface-raised','surface-sunken','action-soft','ready-soft','spark-soft','attention-soft']],
 ['ink-muted',['surface','surface-raised','surface-sunken','action-soft']],
 ['link',['surface','surface-raised','surface-sunken']],
 ['ink-inverse',['surface-inverse']],
 ['on-action',['action']],
 ['ready-ink',['ready-soft']],
 ['spark-ink',['spark-soft']],
 ['attention-ink',['attention-soft','surface-raised']],
];
export function assertContrast(tokens){
 const colors=new Map(tokens.color.tokens.map(t=>[t.name,t.value]));
 const hex=(name,theme)=>{let v=colors.get(name);v=typeof v==='string'?v:v[theme];return v.replace(/^\{([a-z-]+)\}$/,(_,n)=>colors.get(n));};
 for(const theme of ['light','dark']){
  for(const [fg,backs] of textPairs)for(const bg of backs){
   const ratio=contrast(hex(fg,theme),hex(bg,theme));
   assert.ok(ratio>=4.5,`${fg} on ${bg} (${theme}) is ${ratio.toFixed(2)}:1, needs 4.5:1`);
  }
  for(const g of tokens.gradient.tokens)for(const stop of g.value[theme].match(/#[0-9a-f]{6}/gi)){
   const ratio=contrast(hex('ink',theme),stop);
   assert.ok(ratio>=4.5,`ink on ${g.name} stop ${stop} (${theme}) is ${ratio.toFixed(2)}:1, needs 4.5:1`);
  }
 }
}

export async function renderDesignTokens({media=false}={}){
 const tokens=JSON.parse(await readFile(source,'utf8'));
 assertContrast(tokens);
 const colors=tokens.color.tokens;
 const fixed=new Map(colors.filter(t=>typeof t.value==='string').map(t=>[t.name,t.value]));
 const resolve=value=>value.replace(/^\{([a-z-]+)\}$/,(_,name)=>{if(!fixed.has(name))throw new Error('Unknown token reference '+value);return fixed.get(name);});
 const themed=(theme)=>[
  ...colors.filter(t=>typeof t.value!=='string').map(t=>`--${t.name}:${resolve(t.value[theme])}`),
  ...tokens.shadow.tokens.map(t=>`--${t.name}:${t.value[theme]}`),
  ...tokens.gradient.tokens.map(t=>`--${t.name}:${t.value[theme]}`),
 ];
 const type=tokens.type.groups.flatMap(g=>g.styles).flatMap(t=>[
  `--type-${t.name}-size:${t.fontSize}`,`--type-${t.name}-line:${t.lineHeight}`,`--type-${t.name}-weight:${t.fontWeight}`,
  ...(t.letterSpacing?[`--type-${t.name}-tracking:${t.letterSpacing}`]:[]),
 ]);
 const motion=[
  ...tokens.motion.durations.map(t=>`--duration-${t.name}:${t.value}`),
  ...tokens.motion.easings.map(t=>`--ease-${t.name}:${t.value}`),
 ];
 const light=[
  ...[...fixed].map(([name,value])=>`--${name}:${value}`),
  `--font-display-family:${tokens.type.families.display}`,
  `--font-ui-family:${tokens.type.families.ui}`,
  ...type,
  ...motion,
  ...tokens.spacing.tokens.map(t=>`--${t.name}:${t.value}`),
  ...tokens.radius.tokens.map(t=>`--${t.name}:${t.value}`),
  ...themed('light'),
 ];
 return `/* Generated by tools/design-tokens.mjs from docs/design/whumpo-design-system/tokens.json. Do not edit. */\n:root{\n ${light.join(';\n ')};\n}\n.dark{\n ${themed('dark').join(';\n ')};\n}\n${media?`@media(prefers-color-scheme:dark){\n:root{\n ${themed('dark').join(';\n ')};\n}\n}\n`:''}`;
}

// Material 3 role mapping (docs/android/app-ux.md, "Theming"). Entry: [light,dark]; a value is a token name,
// "light:name"/"dark:name" (that theme's value, for inversePrimary) or a literal hex.
const m3=[
 ['primary','link','link'],['onPrimary','#ffffff','deep-sky'],
 ['primaryContainer','action','action'],['onPrimaryContainer','on-action','on-action'],
 ['secondary','deep-sky','ink'],['onSecondary','cloud-white','deep-sky'],
 ['secondaryContainer','action-soft','action-soft'],['onSecondaryContainer','ink','ink'],
 ['tertiary','spark-ink','spark-ink'],['onTertiary','spark-soft','spark-soft'],
 ['tertiaryContainer','spark-soft','spark-soft'],['onTertiaryContainer','spark-ink','spark-ink'],
 ['error','attention-ink','attention-ink'],['onError','#ffffff','deep-sky'],
 ['errorContainer','attention-soft','attention-soft'],['onErrorContainer','attention-ink','attention-ink'],
 ['background','surface','surface'],['onBackground','ink','ink'],['surface','surface','surface'],['onSurface','ink','ink'],
 ['surfaceVariant','surface-sunken','surface-sunken'],['onSurfaceVariant','ink-muted','ink-muted'],
 ['surfaceDim','surface-sunken','surface-sunken'],['surfaceBright','surface-raised','surface-raised'],
 ['surfaceContainerLowest','surface-raised','surface-raised'],['surfaceContainerLow','surface-raised','surface-raised'],
 ['surfaceContainer','surface-sunken','surface-sunken'],['surfaceContainerHigh','surface-sunken','surface-sunken'],
 ['surfaceContainerHighest','surface-sunken','surface-sunken'],['surfaceTint','link','link'],
 ['outline','line-strong','line-strong'],['outlineVariant','line','line'],
 ['inverseSurface','surface-inverse','surface-inverse'],['inverseOnSurface','ink-inverse','ink-inverse'],
 ['inversePrimary','dark:link','light:link'],['scrim','#000000','#000000'],
];
// Text pairs (4.5:1) and non-text pairs (3:1) of the mapped scheme, checked in both themes.
const m3Text=[
 ['onPrimary','primary'],['onPrimaryContainer','primaryContainer'],['onSecondary','secondary'],['onSecondaryContainer','secondaryContainer'],
 ['onTertiary','tertiary'],['onTertiaryContainer','tertiaryContainer'],['onError','error'],['onErrorContainer','errorContainer'],
 ['onSurface','surface'],['onSurface','surfaceContainerLowest'],['onSurface','surfaceContainer'],['onBackground','background'],
 ['onSurfaceVariant','surface'],['onSurfaceVariant','surfaceContainerLowest'],['onSurfaceVariant','surfaceContainer'],['onSurfaceVariant','secondaryContainer'],
 ['primary','surface'],['primary','surfaceContainerLowest'],['primary','surfaceContainer'],
 ['error','surface'],['error','surfaceContainerLowest'],['inverseOnSurface','inverseSurface'],['inversePrimary','inverseSurface'],
];
const m3Border=[['outline','surface'],['outline','surfaceContainerLowest'],['outline','surfaceContainer'],['focusRing','surface'],['focusRing','surfaceContainerLowest'],['focusRing','surfaceContainer']];
export function m3Scheme(tokens,theme){
 const colors=new Map(tokens.color.tokens.map(t=>[t.name,t.value]));
 const val=(name,th)=>{let v=colors.get(name);if(v===undefined)throw new Error('Unknown token '+name);v=typeof v==='string'?v:v[th];return v.replace(/^\{([a-z-]+)\}$/,(_,n)=>colors.get(n));};
 const pick=(ref)=>ref.startsWith('#')?ref:/^(light|dark):/.test(ref)?val(ref.slice(ref.indexOf(':')+1),ref.slice(0,ref.indexOf(':'))):val(ref,theme);
 const scheme=Object.fromEntries(m3.map(([role,l,d])=>[role,pick(theme==='light'?l:d)]));
 scheme.focusRing=val('focus-ring',theme);
 return scheme;
}
export function assertM3Contrast(tokens){
 for(const theme of ['light','dark']){
  const s=m3Scheme(tokens,theme);
  for(const [fg,bg] of m3Text)assert.ok(contrast(s[fg],s[bg])>=4.5,`M3 ${fg} on ${bg} (${theme}) is ${contrast(s[fg],s[bg]).toFixed(2)}:1, needs 4.5:1`);
  for(const [fg,bg] of m3Border)assert.ok(contrast(s[fg],s[bg])>=3,`M3 ${fg} on ${bg} (${theme}) is ${contrast(s[fg],s[bg]).toFixed(2)}:1, needs 3:1`);
 }
 assert.notEqual(m3Scheme(tokens,'light').primary.toLowerCase(),tokens.color.tokens.find(t=>t.name==='sky-blue').value,'light primary must not be Sky Blue');
}

const camel=n=>n.replace(/-([a-z0-9])/g,(_,c)=>c.toUpperCase());
const pascal=n=>{const c=camel(n);return c[0].toUpperCase()+c.slice(1);};
const argb=h=>'0xFF'+h.slice(1).toUpperCase()+'L';
const f=v=>{const n=String(parseFloat(v));return (n.includes('.')?n:n+'.0')+'f';};
export async function renderKotlinTokens(){
 const tokens=JSON.parse(await readFile(source,'utf8'));
 assertContrast(tokens);assertM3Contrast(tokens);
 const colors=tokens.color.tokens;
 const fixed=colors.filter(t=>typeof t.value==='string');
 const themedColors=colors.filter(t=>typeof t.value!=='string');
 const resolve=(v)=>v.replace(/^\{([a-z-]+)\}$/,(_,n)=>fixed.find(t=>t.name===n).value);
 const styles=tokens.type.groups.flatMap(g=>g.styles.map(t=>({...t,family:g.family})));
 const pal=th=>`WhumpoPalette(\n${themedColors.map(t=>`        ${camel(t.name)} = ${argb(resolve(t.value[th]))},`).join('\n')}\n    )`;
 const scheme=th=>`WhumpoScheme(\n${[...m3.map(([r])=>r),'focusRing'].map(r=>`        ${r} = ${argb(m3Scheme(tokens,th)[r])},`).join('\n')}\n    )`;
 const roles=[...m3.map(([r])=>r),'focusRing'];
 return `// Generated by tools/design-tokens.mjs from docs/design/whumpo-design-system/tokens.json. Do not edit.
package com.whumpo.android.ui.theme

/** Colours are ARGB longs so the tokens stay free of Compose and testable on the JVM. */
class WhumpoPalette(
${themedColors.map(t=>`    val ${camel(t.name)}: Long,`).join('\n')}
)

/** Material 3 colour roles after the Whumpo mapping (docs/android/app-ux.md). */
class WhumpoScheme(
${roles.map(r=>`    val ${r}: Long,`).join('\n')}
)

/** Type token. [display] selects Poppins; otherwise Inter. Sizes are sp, tracking is em. */
class WhumpoTypeToken(val display: Boolean, val size: Float, val line: Float, val weight: Int, val tracking: Float)

class WhumpoBezier(val x1: Float, val y1: Float, val x2: Float, val y2: Float)

object WhumpoTokens {
${fixed.map(t=>`    const val Brand${pascal(t.name)}: Long = ${argb(t.value)}`).join('\n')}

    val Light = ${pal('light')}

    val Dark = ${pal('dark')}

    val LightScheme = ${scheme('light')}

    val DarkScheme = ${scheme('dark')}

${styles.map(t=>`    val Type${pascal(t.name)} = WhumpoTypeToken(display = ${t.family==='display'}, size = ${f(t.fontSize)}, line = ${f(t.lineHeight)}, weight = ${t.fontWeight}, tracking = ${f(t.letterSpacing??'0')})`).join('\n')}

${tokens.radius.tokens.map(t=>`    const val ${pascal(t.name)}Dp: Int = ${t.name==='radius-full'?9999:parseInt(t.value)}`).join('\n')}

${tokens.spacing.tokens.map(t=>`    const val ${pascal(t.name)}Dp: Int = ${parseInt(t.value)}`).join('\n')}

${tokens.motion.durations.map(t=>`    const val Duration${pascal(t.name)}Ms: Int = ${parseInt(t.value)}`).join('\n')}

${tokens.motion.easings.map(t=>`    val Ease${pascal(t.name)} = WhumpoBezier(${t.value.match(/[\d.]+/g).map(f).join(', ')})`).join('\n')}
}
`;
}

let stale=false;
{
 const kt=await renderKotlinTokens();
 const url=new URL('../android/shared/src/commonMain/kotlin/com/whumpo/android/ui/theme/WhumpoTokens.kt',import.meta.url);
 if(process.argv.includes('--check')){
  if(await readFile(url,'utf8').catch(()=>'')!==kt){console.error('WhumpoTokens.kt is stale. Run node tools/design-tokens.mjs');stale=true;}
 }else{await mkdir(dirname(fileURLToPath(url)),{recursive:true});await writeFile(url,kt);}
}
for(const {path,media,url} of targets){
 const css=await renderDesignTokens({media});
 if(process.argv.includes('--check')){
  if(await readFile(url,'utf8').catch(()=>'')!==css){console.error(path+' is stale. Run node tools/design-tokens.mjs');stale=true;}
 }else await writeFile(url,css);
}
if(stale)process.exit(1);
