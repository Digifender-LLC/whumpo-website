import {saveBuildSnapshot,readBuildInputs} from './build-snapshot.mjs';
import {build as viteBuild} from 'vite';
import {build} from 'esbuild';
import {checkSpecificationCompiler} from './check-specification-compiler.mjs';
const buildInputs=await readBuildInputs();
await checkSpecificationCompiler();
await viteBuild();
// The controlled visitor page is a separate deployment and trust boundary.
await build({entryPoints:['web/visitor.js'],bundle:true,format:'iife',target:'es2022',outfile:'public-app/visitor.js',banner:{js:'// Generated by tools/build.mjs. Edit web/visitor.js instead.'}});

await saveBuildSnapshot(process.cwd(),buildInputs);
