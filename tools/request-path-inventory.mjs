const cell=v=>String(v).replaceAll('|','\\|');
export function markdown(inventory){
 const lines=['| Route class | Entry Worker (config) | Worker runs | Status | `cache-control` | D1 statements (reads/writes; calls+batches) | R2 | Service hops | Subrequests | Revocation inputs read | Repeat |','| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |'];
 for(const r of inventory.routes){
  const f=r.firstRequest,d=f.d1,r2=Object.entries(f.r2).map(([k,v])=>k+' '+v).join(', ')||'0',hops=r.workerExecution.serviceBindingTargets.map(t=>`${t.binding} ${f.serviceBindings[t.binding]} → ${t.worker}${t.runs===true?' (Worker runs: run_worker_first)':''}`).join(', ')||'0';
  const entry=r.entry.worker?`${r.entry.worker} (\`${r.entry.route}\`)`:'none routed (code path only)';
  const runs=r.workerExecution.runs===true?(r.workerExecution.reason.startsWith('no assets')?'yes (no assets)':'yes (run_worker_first)'):'asset-first';
  const extra=[f.assetsBinding?'ASSETS '+f.assetsBinding:'',Object.keys(f.rateLimiter).length?'limiter '+Object.values(f.rateLimiter).reduce((a,b)=>a+b,0):'',f.waitUntil?'waitUntil '+f.waitUntil:''].filter(Boolean).join('; ');
  lines.push('| '+[`${cell(r.label)} \`${r.method} ${cell(r.url)}\``,entry,runs,r.status,`\`${cell(r.cacheControl)}\``+(r.assetsStub&&r.cacheControl===null?' (ASSETS stub)':''),`${d.statements} (${d.reads}/${d.writes}; ${d.calls}+${d.batches})`,r2,hops+(extra?'; '+extra:''),f.subrequests.length,r.revocationInputs.join('; ')||'none',r.repeatRequest.sameWork?(r.repeatRequest.bodyIdentical?'same work, same body':'same work, body differs'):'work differs'].join(' | ')+' |');
 }
 lines.push('','| Revocation probe | Change | Before | After (status, `cache-control`) |','| --- | --- | --- | --- |');
 for(const p of inventory.revocation)lines.push(`| ${p.signal} | ${cell(p.change)} | ${Object.entries(p.before).map(([k,v])=>k+' '+v).join(', ')} | ${Object.entries(p.after).map(([k,v])=>`${k} ${v.status} \`${v.cacheControl}\``).join(', ')} |`);
 return lines.join('\n');
}
export const serialize=inventory=>JSON.stringify(inventory,null,1)+'\n';
/** Returns the drift messages between a measured inventory and the committed JSON and markdown block. */
export async function drift(inventory){
 const problems=[],committed=await readFile(resolve(root,inventoryPath),'utf8').catch(()=>null);
 const {database,...measured}=inventory;
 if(committed===null)problems.push(inventoryPath+' is missing');
 else{const {database:_,...saved}=JSON.parse(committed);if(JSON.stringify(saved)!==JSON.stringify(measured))problems.push(inventoryPath+' differs from the measured inventory');}
 const doc=await readFile(resolve(root,markdownPath),'utf8'),start=doc.indexOf(markers[0]),end=doc.indexOf(markers[1]);
 if(start<0||end<start)problems.push(markdownPath+' lacks the generated table markers');
 else if(doc.slice(start+markers[0].length,end).trim()!==markdown(inventory))problems.push(markdownPath+' table differs from the measured inventory');
 return problems;
}
export async function write(inventory){
 await writeFile(resolve(root,inventoryPath),serialize(inventory));
 const doc=await readFile(resolve(root,markdownPath),'utf8'),start=doc.indexOf(markers[0]),end=doc.indexOf(markers[1]);
 assert.ok(start>=0&&end>start,'Add the generated table markers to '+markdownPath+' first');
 await writeFile(resolve(root,markdownPath),doc.slice(0,start+markers[0].length)+'\n'+markdown(inventory)+'\n'+doc.slice(end));
}

