const glob=pattern=>new RegExp('^'+pattern.split('*').map(s=>s.replace(/[.+?^${}()|[\]\\]/g,'\\$&')).join('.*')+'$');
/** Which Worker a public URL reaches under the configured routes (custom domains match their host; zone routes host/path globs). */
export function entryWorker(workers,url){
 const u=new URL(url),matches=[];
 for(const [name,w] of Object.entries(workers))for(const r of w.routes){
  const slash=r.pattern.indexOf('/'),host=slash<0?r.pattern:r.pattern.slice(0,slash),path=r.customDomain||slash<0?'/*':r.pattern.slice(slash);
  if(glob(host).test(u.hostname)&&glob(path).test(u.pathname))matches.push({worker:name,route:r.pattern});
 }
 assert.ok(matches.length<=1,'Overlapping routes for '+url+': '+JSON.stringify(matches));
 return matches[0]??null;
}
/** Whether the Worker script runs for this path, per the Static Assets `run_worker_first` rules. */
export function workerRuns(worker,path){
 if(!worker.assets)return {runs:true,reason:'no assets configured; every routed request invokes the Worker'};
 const first=worker.assets.runWorkerFirst;
 if(first===true)return {runs:true,reason:'assets.run_worker_first = true; every request invokes the Worker before any asset'};
 if(Array.isArray(first)){
  const excluded=first.filter(p=>p.startsWith('!')).some(p=>glob(p.slice(1)).test(path)),included=first.filter(p=>!p.startsWith('!')).some(p=>glob(p).test(path));
  if(included&&!excluded)return {runs:true,reason:'path matches assets.run_worker_first'};
 }
 return {runs:'only-if-no-asset',reason:'asset-first: a matching static asset is served without invoking the Worker'};
}

